const pick = (arr, start, count, exclude) => {
    const res = [];
    let i = start;
    while (res.length < count) {
        const item = arr[i % arr.length];
        if (item !== exclude && !res.includes(item)) res.push(item);
        i += 1;
    }
    return res;
};

